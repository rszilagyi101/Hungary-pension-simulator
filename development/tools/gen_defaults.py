"""Generate assets/js/ps-defaults.js from the Python project (single source of truth).

usage: python tools/gen_defaults.py ../pension_sim
"""
import json
import sys
from pathlib import Path

import pandas as pd

src = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(src))
from core import data_sources as ds, exporters, scenarios, settings  # noqa: E402

data = src / "data"


def rows(df):
    out = []
    for r in df.to_dict("records"):
        out.append({k: (None if (isinstance(v, float) and v != v) else v) for k, v in r.items()})
    return out


hist = pd.read_csv(data / "default_history.csv").drop(columns=["source"], errors="ignore")
proj = pd.read_csv(data / "default_projection.csv").drop(columns=["source"], errors="ignore")
ages = pd.read_csv(data / "ksh_age_sex.csv")
ages_w = {}
for (y, s), g in ages.groupby(["year", "sex"]):
    g = g.sort_values("age")
    ages_w.setdefault(s, {})[int(y)] = [float(v) for v in g["population"].tolist()]
vital = pd.read_csv(data / "ksh_vital.csv")

out = {
    "spec": settings.SPEC,
    "modelKeys": settings.MODEL_KEYS,
    "modelLabels": settings.MODEL_LABELS,
    "columns": ds.COLUMNS,
    "columnLabels": ds.COLUMN_LABELS,
    "aliases": ds._ALIASES,
    "scenarioParams": scenarios.public_params(),
    "categoryLabels": scenarios.CATEGORY_LABELS,
    "sources": exporters.SOURCES_TEXT,
    "defaultHistory": rows(hist),
    "defaultProjection": rows(proj),
    "kshAges": ages_w,          # {M|F: {year: [91 values, ages 0..89, 90+]}}
    "vital": rows(vital),
}
js = ("/* Generated by tools/gen_defaults.py from the KSH tables bundled with the simulator. Do not edit. */\n"
      "globalThis.PS_DEFAULTS = " + json.dumps(out, ensure_ascii=False, separators=(",", ":")) + ";\n")
_root = Path(__file__).resolve().parent.parent
_out = (_root if (_root / "index.html").exists() else _root.parent / "site") / "assets/js/ps-defaults.js"
_out.write_text(js, encoding="utf-8")
print("wrote assets/js/ps-defaults.js", len(js) // 1024, "KB;",
      len(out["spec"]), "settings,", len(out["scenarioParams"]), "scenario parameters,",
      len(ages_w["M"]), "age-structure years")
